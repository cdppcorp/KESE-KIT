def norm_text(value: str) -> str:
    return WS_RE.sub(" ", value.replace("\xa0", " ")).strip()


# --------------------------------------------------------------------------- HTML tables


@dataclass
class _Cell:
    text: list[str] = field(default_factory=list)
    rowspan: int = 1
    colspan: int = 1


@dataclass
class _Table:
    rows: list[list[_Cell]] = field(default_factory=list)
    row: list[_Cell] | None = None
    cell: _Cell | None = None


class TableExtractor(HTMLParser):
    """Collect every <table> as a list of rows of raw cells (spans not yet expanded)."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self._stack: list[_Table] = []
        self.tables: list[list[list[_Cell]]] = []

    @staticmethod
    def _span(attrs: list[tuple[str, str | None]], name: str) -> int:
        for key, value in attrs:
            if key == name and value:
                digits = re.sub(r"\D", "", value)
                if digits:
                    return max(1, min(int(digits), 500))
        return 1

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "table":
            self._stack.append(_Table())
            return
        if not self._stack:
            return
        table = self._stack[-1]
        if tag == "tr":
            self._close_row(table)
            table.row = []
        elif tag in ("td", "th"):
            if table.row is None:
                table.row = []
            self._close_cell(table)
            table.cell = _Cell(rowspan=self._span(attrs, "rowspan"), colspan=self._span(attrs, "colspan"))
        elif tag in ("br", "p", "div", "li") and table.cell is not None:
            table.cell.text.append(" ")

    def handle_endtag(self, tag: str) -> None:
        if not self._stack:
            return
        table = self._stack[-1]
        if tag in ("td", "th"):
            self._close_cell(table)
        elif tag == "tr":
            self._close_row(table)
        elif tag == "table":
            self._close_row(table)
            finished = self._stack.pop()
            if finished.rows:
                self.tables.append(finished.rows)
            # Nested table text also belongs to the enclosing cell.
            if self._stack and self._stack[-1].cell is not None:
                flat = " ".join("".join(c.text) for r in finished.rows for c in r)
                self._stack[-1].cell.text.append(" " + flat)

    def handle_data(self, data: str) -> None:
        if self._stack and self._stack[-1].cell is not None:
            self._stack[-1].cell.text.append(data)

    @staticmethod
    def _close_cell(table: _Table) -> None:
        if table.cell is not None and table.row is not None:
            table.row.append(table.cell)
        table.cell = None

    def _close_row(self, table: _Table) -> None:
        self._close_cell(table)
        if table.row is not None:  # keep empty <tr>: rowspans extend into it
            table.rows.append(table.row)
        table.row = None

    def close(self) -> None:
        super().close()
        while self._stack:  # unbalanced HTML: flush tables that were never closed
            self.handle_endtag("table")


def expand_grid(raw_rows: list[list[_Cell]]) -> list[list[str]]:
    """Expand rowspan/colspan into a rectangular grid of normalised strings."""
    grid: list[list[str]] = []
    carry: dict[int, tuple[str, int]] = {}  # column → (text, rows remaining)
    for raw in raw_rows:
        if not raw:
            # An empty <tr> is a real row that rowspans extend into, but it carries no data of its own.
            carry = {c: (t, n - 1) for c, (t, n) in carry.items() if n > 1}
            continue
        row: list[str] = []
        col = 0
        cells = iter(raw)
        pending = next(cells, None)
        while pending is not None or any(c >= col for c in carry):
            if col in carry:
                text, remaining = carry[col]
                row.append(text)
                if remaining <= 1:
                    del carry[col]
                else:
                    carry[col] = (text, remaining - 1)
                col += 1
                continue
            if pending is None:
                # Gap before a carried column further right.
                row.append("")
                col += 1
                continue
            text = norm_text("".join(pending.text))
            for _ in range(pending.colspan):
                row.append(text)
                if pending.rowspan > 1:
                    carry[col] = (text, pending.rowspan - 1)
                col += 1
            pending = next(cells, None)
        grid.append(row)
    width = max((len(r) for r in grid), default=0)
    return [r + [""] * (width - len(r)) for r in grid]


def parse_tables(html: str) -> list[list[list[str]]]:
    parser = TableExtractor()
    parser.feed(html)
    parser.close()
    return [expand_grid(t) for t in parser.tables]


# --------------------------------------------------------------------------- table semantics


def classify_header(cell: str) -> str | None:
    h = cell.replace(" ", "")
    low = h.lower()
    if not h:
        return None
    if any(k in h for k in ("제목", "설명", "내용")):
        return "description"
    if any(k in h for k in ("제조사", "벤더", "개발사")) or "vendor" in low:
        return "vendor"
    if "생태계" in h or "ecosystem" in low:
        return "ecosystem"
    has_version = "버전" in h or "version" in low
    if has_version:
        if any(k in h for k in ("해결", "패치", "수정", "권장", "업데이트", "조치", "최신", "안전")) or "fixed" in low:
            return "fixed"
        return "affected"
    if "cve" in low or h.startswith("취약점") and not any(k in h for k in ("설명", "내용", "유형")):
        return "cve"
    if any(k in h for k in ("해결", "패치", "조치", "대응")):
        return "fixed"
    if any(k in h for k in ("제품", "대상", "구성요소", "플러그인", "소프트웨어", "모델", "모듈", "OS")) or "product" in low:
        return "product"
    if any(k in h for k in ("심각도", "위험도", "중요도")) or "cvss" in low:
        return "severity"
    if "유형" in h:
        return "description"
    return None


def find_header(grid: list[list[str]]) -> int | None:
    for idx, row in enumerate(grid[:3]):
        if any(len(cell) > HEADER_CELL_MAX_CHARS for cell in row):
            continue
        if len(row) > 1 and len({cell for cell in row if cell}) <= 1:
            continue  # caption row spanning the whole table
        joined = " ".join(row)
        hits = sum(1 for t in HEADER_TERMS if t in joined)
        if hits >= 2 and not CVE_RE.search(joined):
            return idx
    return None


def table_to_rows(grid: list[list[str]]) -> tuple[list[dict], dict | None, int]:
    """Return (mapped rows, unmapped table, data cells lost under blank header cells)."""
    header_idx = find_header(grid)
    if header_idx is None:
        return [], {"rows": grid}, 0
    header = grid[header_idx]
    fields = [classify_header(h) for h in header]
    if not any(f in ("product", "affected", "fixed") for f in fields):
        return [], {"header": header, "rows": grid[header_idx + 1 :]}, 0
    rows: list[dict] = []
    lost = 0
    for raw in grid[header_idx + 1 :]:
        if raw == header or not any(raw):
            continue
        lost += sum(1 for h, value in zip(header, raw) if value and not h)
        record = row_record(fields, raw)
        if record:
            rows.append(record)
    return dedupe_rows(rows), None, lost


def row_record(fields: list[str | None], raw: list[str]) -> dict[str, str]:
    record: dict[str, str] = {}
    for name, value in zip(fields, raw):
        if not (name and value):
            continue
        if name not in record:
            record[name] = value
        elif value not in record[name]:
            record[name] = f"{record[name]} / {value}"
    # Some tables put the vulnerability *type* under "취약점"; keep only real CVE ids there.
    if "cve" in record and not CVE_RE.search(record["cve"]):
        kind = record.pop("cve")
        record["description"] = f"{kind} / {record['description']}" if "description" in record else kind
    if record and "cve" not in record:
        found = sorted(set(CVE_RE.findall(" ".join(raw))))
        if found:
            record["cve"] = ", ".join(found)
    return record


def is_data_table(rows: list[list[str]]) -> bool:
    """False for empty tables and the single-column wrappers KISA uses for page layout."""
    width = max((len(r) for r in rows), default=0)
    return width >= 2 and any(any(c for c in r) for r in rows)


def dedupe_rows(rows: list[dict]) -> list[dict]:
    seen: set[tuple] = set()
    unique: list[dict] = []
    for row in rows:
        key = tuple(sorted(row.items()))
        if key not in seen:
            seen.add(key)
            unique.append(row)
    return unique


# --------------------------------------------------------------------------- text helpers


def split_sections(text: str) -> dict[str, str]:
    """Split a 본문.txt body on '□ heading' markers."""
    body = text.split("\n\n", 1)[1] if "\n\n" in text else text
    sections: dict[str, str] = {}
    for chunk in re.split(r"□\s*", body)[1:]:
        chunk = norm_text(chunk)
        heading, _, rest = chunk.partition(" ")
        if heading in ("영향받는", "영향", "해결", "참고", "참고사이트", "문의사항", "작성:"):
            heading = chunk.split(" o ", 1)[0][:30]
        sections.setdefault(heading, rest)
    return sections


def make_summary(text: str) -> str:
    sections = split_sections(text)
    for key in ("설명", "주요내용", "주요", "개요", "내용"):
        for heading, body in sections.items():
            if heading.startswith(key) and body:
                return clip(body, SUMMARY_MAX_CHARS)
    body = text.split("\n\n", 1)[1] if "\n\n" in text else text
    return clip(norm_text(body), SUMMARY_MAX_CHARS)


def clip(value: str, limit: int) -> str:
    value = norm_text(value)
    return value if len(value) <= limit else value[: limit - 1].rstrip() + "…"


def vendor_from_title(title: str) -> str:
    stripped = re.sub(r"^\(.*?\)\s*", "", title).strip()
    for pattern, vendor in VENDOR_ALIASES:
        if pattern.search(stripped):
            return vendor
    match = TITLE_STOP_RE.search(stripped)
    if match and match.start() > 0:
        return re.sub(r"社|\(주\)", "", stripped[: match.start()]).strip(" ,·")
    return "기타"


# --------------------------------------------------------------------------- records


def load_index(source: Path) -> list[dict]:
    with (source / INDEX_CSV).open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def read_optional(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""


def body_of(text: str) -> str:
    """본문.txt without its title/date/source header block."""
    return text.split("\n\n", 1)[1] if "\n\n" in text else text


def searchable_text(text: str) -> str:
    return clip(URL_RE.sub(" ", body_of(text)), TEXT_MAX_CHARS)


def clean_url(url: str) -> str:
    return url.rstrip(URL_TRAILING_CHARS)


def extract_refs(text: str) -> list[dict]:
    """Reference links from the visible body (never from href attributes, which hold editor residue).

    Numbered '□ 참고사이트 [n] url' entries come first, then any other URLs (vendor download
    pages, MSRC guides, ...) without a number.
    """
    body = body_of(text)
    refs: list[dict] = []
    seen: set[str] = set()
    for number, url in REF_RE.findall(body):
        url = clean_url(url)
        key = f"{number} {url}"
        if url and key not in seen:
            seen.add(key)
            refs.append({"n": number, "url": url})
    numbered = {r["url"] for r in refs}
    for url in REF_URL_RE.findall(body):
        url = clean_url(url)
        if url and url not in numbered and url not in seen:
            seen.add(url)
            refs.append({"url": url})
    return refs


def build_record(row: dict, source: Path) -> tuple[dict, list[str]]:
    """Return (record, build warnings) for one 목록.csv row."""
    folder = source / row["폴더경로"]
    text = read_optional(folder / BODY_TXT)
    html = read_optional(folder / BODY_HTML)
    issues: list[str] = []
    if not text and not html:
        issues.append("본문.txt/본문.html missing")
    affected: list[dict] = []
    other_tables: list[dict] = []
    lost = 0
    for grid in parse_tables(html):
        rows, unmapped, dropped = table_to_rows(grid)
        affected.extend(rows)
        lost += dropped
        if unmapped and is_data_table(unmapped["rows"]):
            other_tables.append(unmapped)
    if lost:
        issues.append(f"{lost} table cell(s) under blank header cells were dropped")
    url = row["원문링크"].strip()
    if not url.startswith(SOURCE_URL_PREFIX):
        issues.append(f"unexpected source URL {url!r}")
        url = ""
    ntt = NTT_RE.search(url)
    attachments = [a.strip() for a in row.get("첨부파일명", "").split("|") if a.strip()]
    if not attachments and folder.exists():
        attachments = sorted(p.name for p in folder.iterdir() if p.is_file() and not p.name.startswith("본문."))
    record = {
        "no": row["번호"],
        "ntt": ntt.group(1) if ntt else "",
        "date": row["게시일"],
        "type": row["유형"],
        "title": row["제목"],
        "vendor": vendor_from_title(row["제목"]),
        "url": url,
        "folder": row["폴더경로"],
        "attachments": attachments,
        "summary": make_summary(text),
        "refs": extract_refs(text),
        # Visible text only: KISA's editor leaves hidden <a href> residue with unrelated CVE ids.
        "cves": sorted(set(CVE_RE.findall(text)) | {c for r in affected for c in CVE_RE.findall(r.get("cve", ""))}),
        "affected": dedupe_rows(affected),
        "text": searchable_text(text),
    }
    if other_tables:
        record["tables"] = other_tables
    if not record["ntt"]:
        issues.append("no nttId in source URL")
    return record, issues


def build_records(source: Path) -> list[dict]:
    records: list[dict] = []
    for row in load_index(source):
        record, issues = build_record(row, source)
        for issue in issues:
            print(f"warning: #{row.get('번호')} {row.get('게시일')} {row.get('제목')}: {issue}", file=sys.stderr)
        records.append(record)
    return sorted(records, key=lambda r: (r["date"], int(r["ntt"] or 0)), reverse=True)


